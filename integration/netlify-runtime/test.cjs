const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const plugin = require('./index.cjs');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'innova-adapter-'));
const handler = path.join(root, '___netlify-server-handler');
const nested = path.join(handler, '.netlify', 'dist', 'run');
fs.mkdirSync(nested, { recursive: true });
const file = path.join(nested, 'constants.js');
fs.writeFileSync(file, 'var PLUGIN_DIR = resolve(`${MODULE_DIR}../../..`);');
fs.writeFileSync(path.join(handler, 'run-config.json'), '{}');
plugin.onBuild({ constants: { INTERNAL_FUNCTIONS_SRC: root } });
const patched = fs.readFileSync(file, 'utf8');
assert.match(patched, /existsSync/);
const expression = patched.split('var PLUGIN_DIR = ')[1].replace(/;$/, '');
const resolveConfig = new Function('MODULE_DIR', 'resolve', 'existsSync', `return ${expression}`);
assert.equal(resolveConfig(nested + path.sep, path.resolve, fs.existsSync), handler);
assert.equal(path.resolve(resolveConfig(handler + path.sep, path.resolve, fs.existsSync)), handler);
assert.throws(() => plugin.onBuild({ constants: { INTERNAL_FUNCTIONS_SRC: root } }), /layout changed/);
console.log('Runtime compatibility: original layout, flattened layout and change guard passed.');
